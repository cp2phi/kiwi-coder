# 📏 用变量画正方形  A square drawn with a variable
# 只改第 7 行的数字，整个正方形一起变！ Change only the number on line 7 and the whole square changes!

import turtle

t = turtle.Turtle()
size = 100

t.color("deepskyblue")
t.pensize(4)
t.forward(size)
t.left(90)
t.forward(size)
t.left(90)
t.forward(size)
t.left(90)
t.forward(size)
t.left(90)
