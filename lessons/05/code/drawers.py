# 📦 列表：一排带编号的抽屉 / A list: a row of numbered drawers
# 注意：编号从 0 开始！/ Careful: numbering starts at 0!

animals = ["kiwi", "tui", "pukeko"]

print(animals)          # 整个列表 / the whole list
print(animals[0])       # 第 0 个抽屉 / drawer 0
print(animals[1])
print(animals[2])
print(len(animals))     # 一共几个抽屉？/ how many drawers?
